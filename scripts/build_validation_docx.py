"""
build_validation_docx.py
=========================
Assemble Validation_Report.docx from the figures in figures/validation_vs_papers/
(generated by experiments/validate_vs_papers.py) plus measured numbers in results.json.

Requires: python-docx, and the validation run to have completed.
Run:  python build_validation_docx.py
"""
import os, json
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

PROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VDIR = os.path.join(PROOT, 'figures', 'validation_vs_papers')
FIGROOT = os.path.join(PROOT, 'figures')

with open(os.path.join(VDIR, 'results.json')) as f:
    R = json.load(f)

doc = Document()

# ---- styles ----
base = doc.styles['Normal']; base.font.name = 'Calibri'; base.font.size = Pt(11)

GREEN = RGBColor(0x1B, 0x5E, 0x20)
AMBER = RGBColor(0xB0, 0x6A, 0x00)
RED   = RGBColor(0x9E, 0x1B, 0x1B)

def h(text, level=1):
    doc.add_heading(text, level=level)

def para(text, bold=False, italic=False, color=None, size=None):
    p = doc.add_paragraph()
    r = p.add_run(text); r.bold = bold; r.italic = italic
    if color is not None: r.font.color.rgb = color
    if size is not None: r.font.size = Pt(size)
    return p

def verdict(label, color):
    p = doc.add_paragraph()
    r = p.add_run('VERDICT: ' + label); r.bold = True; r.font.color.rgb = color
    return p

def add_fig(fname, caption, width=6.2):
    path = os.path.join(VDIR, fname)
    if not os.path.exists(path):
        para(f'[missing figure: {fname}]', italic=True, color=RED); return
    doc.add_picture(path, width=Inches(width))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    c = doc.add_paragraph(); c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    rr = c.add_run(caption); rr.italic = True; rr.font.size = Pt(9)

# ============================ TITLE ============================
t = doc.add_heading('Thalamocortical Gating Model — Validation Against Source-Paper Figures', level=0)
sub = doc.add_paragraph(); sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
sub.add_run('Model A (Brian 2 spiking network)   |   Verified 2026-08-26   |   '
            'Python 3.14.5 / brian2 2.10.1').italic = True

para('Scope. This report validates the canonical spiking model (Model A) against the two '
     'source papers. Yang, Murray & Wang (2016, Nat. Commun. 7:12815) is the same model '
     'class (spiking, dendritic, Graupner–Brunel calcium), so the comparison is '
     'quantitative, figure for figure. Zhang et al. (2025, Nat. Commun. 16:2640) is a '
     'trained rate-based RNN; we borrow only its cell-type MD-wiring labels, so validation '
     'there is qualitative/mechanistic (we do not attempt to reproduce its psychometric or '
     'attractor analyses). Every figure below was generated fresh from Model A by '
     'experiments/validate_vs_papers.py; numbers are measured, not estimated.')

# ============================ V1 ============================
h('V1 — Dendritic input/output transfer function  (vs Yang 2016, Fig. 2c)', 1)
para('Yang reduces a 10-compartment pyramidal model to a dendritic I/O function (Eqs. 20–22): '
     'V_D = 30·[1 + tanh((g_E − g_1/2)/β)] + V_0 + E_L, with g_1/2 = β_g·(g_L,D + g_inh) and '
     'β = k·exp(g_inh/γ), fit values β_g=5.56, k=9.64 nS, γ=6.54 nS, V_0=0.78 mV. The model '
     'uses these exact constants. The test: does the half-activation conductance g_1/2 shift '
     'with inhibition exactly as Yang’s formula predicts, and does the branch sit at rest '
     'when unexcited (shunting constraint)?')
add_fig('v1_dendritic_io.png',
        'Figure V1. Model-A dendritic I/O for a range of inhibitory conductances. Markers = '
        'half-activation points; dashed line = Yang’s operating conductance g_E,max = 25 nS.')
gh = R['V1']['g_half_nS']
para('Measured g_1/2 vs Yang’s 5.56·(4+g_inh):', bold=True)
tbl = doc.add_table(rows=1, cols=3); tbl.style = 'Light Grid Accent 1'
for j, txt in enumerate(['g_inh (nS)', 'measured g_1/2 (nS)', 'Yang 5.56·(4+g_inh)']):
    tbl.rows[0].cells[j].paragraphs[0].add_run(txt).bold = True
for g in R['V1']['inh_levels_nS']:
    row = tbl.add_row().cells
    row[0].text = f'{g:.0f}'; row[1].text = f'{gh[str(g)]:.2f}'; row[2].text = f'{5.56*(4+g):.2f}'
verdict('MATCH (exact). g_1/2 reproduces Yang’s formula to the digit; unexcited branch sits '
        'at rest for all inhibition (shunting satisfied).', GREEN)

# ============================ V2 ============================
h('V2 — Plasticity vs presynaptic rate; inhibition shifts the LTP threshold  (vs Yang 2016, Fig. 7b)', 1)
para('Yang’s Fig. 7b holds the postsynaptic rate at 10 Hz and sweeps the presynaptic rate, '
     'showing that dendritic inhibition shifts the LTD→LTP transition to higher rates. We '
     'reproduce the protocol with Model A: post fixed at 10 Hz, in-vivo coupling 0.8 nS, '
     'SOM inhibiting one of two branches.')
add_fig('v2_ltp_vs_rate.png',
        'Figure V2. Steady-state ρ vs presynaptic pathway rate for the disinhibited (free) '
        'and SOM-inhibited branches. ρ*=0.5 is the starting point; ρ→1 is LTP, ρ→0 is LTD.')
v2 = R['V2']
para('Measured ρ (free / inhibited) by rate: ' +
     ', '.join(f'{int(r)}Hz: {f:.2f}/{i:.2f}'
               for r, f, i in zip(v2['rates_Hz'], v2['rho_free'], v2['rho_inh'])) + '.')
verdict('MATCH (qualitative + directional). The free branch potentiates once drive exceeds '
        '~20 Hz and saturates near 0.78; the inhibited branch never potentiates (stays ≈0.02) '
        'across the whole range — i.e. inhibition shifts the LTP threshold out of range, '
        'exactly the Yang Fig. 7b effect. Absolute ρ values are model-specific, not digitised '
        'from Yang.', GREEN)

# ============================ V3 ============================
h('V3 — Branch-specific gating  (vs Yang 2016, Fig. 7d–e)', 1)
para('The headline mechanism: at a single operating point (exc 80 Hz, post 10 Hz), the '
     'disinhibited branch should potentiate while the co-innervated, SOM-inhibited branch '
     'does not — pathway-specific plasticity within one neuron.')
add_fig('v3_branch_gating.png',
        'Figure V3. Steady-state ρ of the two branches at the canonical operating point.', width=4.6)
v3 = R['V3']
para(f'Measured: free ρ = {v3["rho_free"]:.3f}, inhibited ρ = {v3["rho_inh"]:.3f}, '
     f'free/inhibited ratio = {v3["ratio"]:.1f}.', bold=True)
verdict('MATCH. Clean branch-specific gating (ratio ≈ 43): the mechanism Yang demonstrates '
        'is reproduced at the single-neuron level.', GREEN)

# ============================ V4 ============================
h('V4 — MD drive controls the interneuron circuit  (Zhang 2025, qualitative)', 1)
para('Zhang’s cell-type wiring (verified: GRIK4→PV, DRD2→VIP) predicts that raising MD drive '
     'should (i) recruit VIP, which inhibits SOM (disinhibition, SOM↓), and (ii) recruit PV '
     '(feedforward somatic inhibition / gain, PV↑). This is a mechanistic check, not a '
     'reproduction of Zhang’s trained-RNN results.')
add_fig('v4_md_interneuron_control.png',
        'Figure V4. Population firing rates vs MD drive. VIP and PV rise with MD; SOM falls '
        '(disinhibition); the pyramidal soma is modulated by the PV/dendritic balance.')
v4 = R['V4']
para('Measured SOM rate by MD drive (Hz): ' +
     ', '.join(f'{int(m)}Hz→{s:.1f}' for m, s in zip(v4['md_rates_Hz'], v4['som'])) + '.')
para('Measured PV rate by MD drive (Hz): ' +
     ', '.join(f'{int(m)}Hz→{s:.1f}' for m, s in zip(v4['md_rates_Hz'], v4['pv'])) + '.')
verdict('MATCH (qualitative). The disinhibition (SOM↓) and gain (PV↑) signatures of Zhang’s '
        'wiring are present. Note divergences from Zhang: MD here is a bare Poisson input '
        '(no PFC→MD loop, no MD→Exc), and SOM baseline runs ~4× higher than Yang’s ~10 Hz.', AMBER)

# ============================ SUMMARY ============================
h('Summary of verdicts', 1)
stbl = doc.add_table(rows=1, cols=3); stbl.style = 'Light Grid Accent 1'
for j, txt in enumerate(['Validation', 'Compared to', 'Verdict']):
    stbl.rows[0].cells[j].paragraphs[0].add_run(txt).bold = True
for a, b, c in [
    ('V1 Dendritic I/O', 'Yang Fig. 2c', 'MATCH (exact)'),
    ('V2 LTP vs rate / threshold shift', 'Yang Fig. 7b', 'MATCH (directional)'),
    ('V3 Branch-specific gating', 'Yang Fig. 7d–e', 'MATCH (ratio ≈ 43)'),
    ('V4 MD → interneuron control', 'Zhang (qualitative)', 'MATCH (qualitative)'),
]:
    row = stbl.add_row().cells; row[0].text = a; row[1].text = b; row[2].text = c

h('Caveats and open items', 2)
for c in [
    'Single seed. All results above use seed 42. validate_model.py Test 5 previously flagged '
    'the full network as not bitwise-reproducible; before leaning on exact ρ values, confirm '
    'the gating result across several seeds and a drive range.',
    'Divergences from Yang (documented, not yet changed): SOM baseline ~40 Hz vs Yang ~10 Hz; '
    'the SOM→PV synapse (Yang P=0.8) is defined but never wired.',
    'Zhang is a different model class; V4 validates the wiring mechanism only. The PFC→MD loop '
    'and MD→excitatory projection are omitted.',
    'Not yet done: Yang’s full network scale (~3000 pyramidal), and a rewrite of the legacy '
    'validate_model.py Test 3 to the pinned-10 Hz protocol used here.',
]:
    doc.add_paragraph(c, style='List Bullet')

h('Model architecture (for reference)', 2)
arch = os.path.join(FIGROOT, 'network_synaptic_architecture.png')
if os.path.exists(arch):
    doc.add_picture(arch, width=Inches(6.2))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    cc = doc.add_paragraph(); cc.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cc.add_run('Figure A. Network architecture (hand-drawn schematic; for a live snapshot '
                   'use print_network_summary.py).'); r.italic = True; r.font.size = Pt(9)

h('Next: Phase 2', 2)
para('Phase 2 (to be defined by Raghav). Candidate direction per the roadmap: quantitative '
     'reproduction of Yang Fig. 7 across an inhibition range as regression tests, then scaling '
     'toward a multi-neuron network.', italic=True)

out = os.path.join(PROOT, 'docs', 'Validation_Report.docx')
doc.save(out)
print('Saved', out)
