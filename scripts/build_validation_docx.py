"""
build_validation_docx.py
=========================
Assemble docs/Validation_Report.docx: a Methods/Results-style validation report
comparing Model A (Brian 2) against the figures of Yang, Murray & Wang (2016)
and Zhang et al. (2025). Text and figures are generated fresh from
figures/validation_vs_papers/results.json (written by
experiments/validate_vs_papers.py) and figures/network_architecture.png
(written by experiments/generate_network_diagram.py). Numbers are measured,
not estimated or invented for presentation.

Requires: python-docx, and both of the scripts above to have been run first.
Run:  python scripts/build_validation_docx.py
"""
import os, json
from docx import Document
from docx.shared import Inches, Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH

PROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VDIR = os.path.join(PROOT, 'figures', 'validation_vs_papers')
FIGROOT = os.path.join(PROOT, 'figures')

with open(os.path.join(VDIR, 'results.json')) as f:
    R = json.load(f)

doc = Document()

base = doc.styles['Normal']
base.font.name = 'Times New Roman'
base.font.size = Pt(11)


def h(text, level=1):
    doc.add_heading(text, level=level)


def para(text, style=None):
    p = doc.add_paragraph(text, style=style)
    return p


def add_fig(fname_or_path, caption, width=6.0, from_vdir=True):
    path = os.path.join(VDIR, fname_or_path) if from_vdir else fname_or_path
    if not os.path.exists(path):
        para(f'[Figure not found: {path}]')
        return
    doc.add_picture(path, width=Inches(width))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = c.add_run(caption)
    r.italic = True
    r.font.size = Pt(9.5)


def plain_table(headers, rows):
    tbl = doc.add_table(rows=1, cols=len(headers))
    tbl.style = 'Table Grid'
    for j, txt in enumerate(headers):
        tbl.rows[0].cells[j].paragraphs[0].add_run(txt).bold = True
    for row in rows:
        cells = tbl.add_row().cells
        for j, val in enumerate(row):
            cells[j].text = str(val)
    return tbl


# ============================ TITLE ============================
doc.add_heading('Validation of a spiking model of dendritic disinhibitory '
                 'gating against Yang et al. (2016) and Zhang et al. (2025)', level=0)

para('This report compares the simulation results of Model A, a Brian 2 spiking '
     'implementation of a two-compartment pyramidal neuron with disinhibitory '
     'interneuron control, against the published figures of its two source '
     'papers. Yang, Murray and Wang (2016) describe a spiking, dendritic model '
     'with the same mechanism and the same Graupner-Brunel calcium-based '
     'plasticity rule, so the comparison below is quantitative. Zhang et al. '
     '(2025) is a trained rate-based recurrent network; this model borrows only '
     'its cell-type-specific mediodorsal thalamic (MD) projection targets, so '
     'the corresponding comparison is restricted to the qualitative behaviour '
     'of the interneuron circuit under MD drive. All figures were generated by '
     'experiments/validate_vs_papers.py; the numbers reported in the text are '
     'read directly from its output.')

# ============================ METHODS ============================
h('1. Methods', 1)

h('1.1 Model', 2)
para('The model consists of a single pyramidal soma coupled to two dendritic '
     'branches by an ohmic conductance. Each branch receives excitatory input '
     'from a Poisson-distributed cortical pathway subject to a Graupner-Brunel '
     'plasticity rule, and inhibitory input from a population of SOM '
     'interneurons that project to one branch only. A population of PV '
     'interneurons provides feedforward inhibition onto the soma. A population '
     'of VIP interneurons inhibits the SOM population, providing a '
     'disinhibitory pathway. Both PV and VIP populations receive excitatory '
     'drive from an MD thalamic population, modelled as a Poisson group, with '
     'connection probabilities and synaptic weights taken from Zhang et al. '
     '(2025) cell-type labels (MD-GRIK4 to PV; MD-DRD2 to VIP). Passive '
     'membrane properties, synaptic time constants, the dendritic input-output '
     'nonlinearity (their Eqs. 20-22), and the Graupner-Brunel plasticity '
     'constants are taken from Yang, Murray and Wang (2016), Methods, pp. '
     '10-12. Dendritic calcium follows their Eq. 13 (a leaky integral of the '
     'local NMDA current) plus their Eq. 14 (a per-spike back-propagating '
     'action potential transient).')
add_fig(os.path.join(FIGROOT, 'network_architecture.png'),
        'Figure 1. Model A network connectivity. Connection probabilities and '
        'synaptic weights are read from model/parameters.py.',
        from_vdir=False)

h('1.2 Simulation protocol', 2)
para('Simulations were run in Brian 2 (version 2.10.1) under Python 3.14.5, '
     'using exponential Euler integration with a 0.02 ms timestep, except for '
     'plastic synapses, which were integrated with the Heun method. Unless '
     'stated otherwise, results use a fixed random seed (42) and the in-vivo '
     'dendrite-soma coupling conductance reported by Yang et al. (0.8 nS). The '
     'postsynaptic (somatic) firing rate was held at 10 Hz by an external '
     'Poisson source in Sections 2.1-2.3, following the protocol used in Yang '
     'et al., Fig. 7.')

# ============================ RESULTS ============================
h('2. Results', 1)

h('2.1 Dendritic input-output transfer function', 2)
para('Yang et al. reduce a multi-compartment pyramidal model to a closed-form '
     'dendritic transfer function (their Eqs. 20-22): '
     'V_D = 30[1 + tanh((g_E - g_1/2)/beta)] + V_0 + E_L, with '
     'g_1/2 = beta_g (g_L,D + g_inh) and beta = k exp(g_inh/gamma). The fitted '
     'constants (beta_g = 5.56, k = 9.64 nS, gamma = 6.54 nS, V_0 = 0.78 mV) '
     'are used unchanged in Model A. Figure 2 plots the resulting curve for '
     'five inhibitory conductance values; Table 1 compares the measured '
     'half-activation conductance g_1/2 at each level against the closed-form '
     'prediction 5.56(4 + g_inh).')
add_fig('v1_dendritic_io.png',
        'Figure 2. Dendritic depolarisation as a function of excitatory '
        'conductance, for five levels of inhibitory conductance. Markers '
        'indicate the half-activation point at each level.')
gh = R['V1']['g_half_nS']
plain_table(
    ['g_inh (nS)', 'Measured g_1/2 (nS)', 'Predicted 5.56(4+g_inh) (nS)'],
    [[f'{g:.0f}', f'{gh[str(g)]:.2f}', f'{5.56*(4+g):.2f}']
     for g in R['V1']['inh_levels_nS']]
)
para('Table 1. Measured half-activation conductance versus the closed-form '
     'prediction of Yang et al. Eq. 22.')
para('The measured half-activation conductance matches the closed-form '
     'prediction at all five inhibition levels. The dendrite remains at rest '
     'in the absence of excitatory drive regardless of inhibitory conductance, '
     'consistent with GABA-A acting as a shunting rather than a hyperpolarising '
     'current at this reversal potential.')

h('2.2 Rate-dependent plasticity and the threshold-shifting effect of inhibition', 2)
para('Yang et al., Fig. 7b, hold the postsynaptic rate at 10 Hz and vary the '
     'presynaptic pathway rate, showing that dendritic inhibition shifts the '
     'transition from depression to potentiation to higher presynaptic rates. '
     'The same protocol was run in Model A with one branch disinhibited and '
     'one branch inhibited by the SOM population.')
add_fig('v2_ltp_vs_rate.png',
        'Figure 3. Steady-state synaptic efficacy (rho) as a function of '
        'presynaptic pathway rate, for the disinhibited and SOM-inhibited '
        'branches. The dashed line marks the initial condition, rho = 0.5.')
v2 = R['V2']
para('Measured rho (disinhibited / inhibited) by presynaptic rate: ' +
     '; '.join(f'{int(r)} Hz: {f:.2f} / {i:.2f}'
               for r, f, i in zip(v2['rates_Hz'], v2['rho_free'], v2['rho_inh'])) + '.')
para('The disinhibited branch potentiates once the presynaptic rate exceeds '
     'approximately 20 Hz and saturates near rho = 0.78. The inhibited branch '
     'does not potentiate at any rate tested (rho remains at or below 0.02 '
     'throughout), consistent with inhibition shifting the depression-to-'
     'potentiation transition outside the tested range. The absolute values '
     'of rho are specific to this model and are not taken from Yang et al.; '
     'the comparison is with the direction and qualitative shape of the '
     'effect, not with digitised values from their figure.')

h('2.3 Branch-specific gating', 2)
para('At a single operating point (presynaptic rate 80 Hz, postsynaptic rate '
     '10 Hz), Yang et al., Fig. 7d-e, show that a disinhibited branch '
     'potentiates while a co-innervated, inhibited branch does not, '
     'demonstrating pathway-specific plasticity within a single neuron. Figure '
     '4 shows the corresponding result for Model A.')
add_fig('v3_branch_gating.png',
        'Figure 4. Steady-state synaptic efficacy of the disinhibited and '
        'SOM-inhibited branches at the operating point used by Yang et al., '
        'Fig. 7d-e (presynaptic 80 Hz, postsynaptic 10 Hz).', width=4.4)
v3 = R['V3']
para(f'Measured rho: disinhibited = {v3["rho_free"]:.3f}, inhibited = '
     f'{v3["rho_inh"]:.3f} (ratio {v3["ratio"]:.1f}). Branch-specific gating '
     'is reproduced at the single-neuron level under this protocol.')

h('2.4 Thalamic modulation of the interneuron circuit', 2)
para('Zhang et al. report that MD projections onto PV neurons (their '
     'GRIK4-expressing population) and onto VIP neurons (their DRD2-expressing '
     'population) are anatomically and functionally distinct; the marker-to-'
     'target assignment used here was verified against their report and is '
     'not reversed. Because Zhang et al. is a trained rate model rather than a '
     'spiking circuit of this type, the comparison here is restricted to '
     'whether increasing MD drive produces the expected qualitative pattern: '
     'recruitment of VIP, a corresponding decrease in SOM firing (disinhibition), '
     'and recruitment of PV.')
add_fig('v4_md_interneuron_control.png',
        'Figure 5. Population firing rates of VIP, SOM, PV, and the pyramidal '
        'soma as a function of MD thalamic drive.')
v4 = R['V4']
para('Measured SOM rate by MD drive (Hz): ' +
     '; '.join(f'{int(m)} -> {s:.1f}' for m, s in zip(v4['md_rates_Hz'], v4['som'])) + '.')
para('Measured PV rate by MD drive (Hz): ' +
     '; '.join(f'{int(m)} -> {s:.1f}' for m, s in zip(v4['md_rates_Hz'], v4['pv'])) + '.')
para('SOM firing decreases from approximately 36 Hz to 0 Hz as MD drive '
     'increases, and PV firing increases monotonically over the same range, '
     'consistent with the disinhibition and gain-control signatures implied '
     'by the Zhang et al. wiring. Two departures from Zhang et al. should be '
     'noted when interpreting this result: MD here is an unstructured Poisson '
     'input with no corticothalamic feedback loop and no direct MD projection '
     'to pyramidal cells, and the SOM baseline firing rate in this model '
     '(approximately 36-40 Hz) is roughly four times the value reported by '
     'Yang et al. for the same cell type (approximately 10 Hz).')

# ============================ LIMITATIONS ============================
h('3. Limitations', 1)
para('The results above were obtained from a single random seed (42). A '
     'previous internal test flagged the full network as not exactly '
     'reproducible across seeds; the gating result in Section 2.3 should be '
     'confirmed across multiple seeds before it is relied on quantitatively.')
para('Two documented departures from Yang et al. have not been corrected: the '
     'SOM baseline firing rate is approximately four times higher than '
     'reported, and the SOM-to-PV synapse described by Yang et al. '
     '(connection probability 0.8) is defined in the parameter file but is '
     'not instantiated in the network.')
para('Zhang et al. is a different class of model (a trained rate network); '
     'Section 2.4 validates the qualitative direction of its wiring only. Its '
     'corticothalamic feedback loop and its direct MD-to-excitatory projection '
     'are not implemented here.')
para('The network in this report is a single pyramidal neuron with two '
     'dendritic branches and twenty interneurons of each type. The '
     'approximately 3,000-neuron network scale used by Yang et al. has not '
     'been attempted. A separate, older verification script '
     '(experiments/validate_model.py) uses a configuration that predates the '
     'protocol used in this report and has not been re-run since; its result '
     'should not be combined with the figures above.')

